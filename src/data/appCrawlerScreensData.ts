/**
 * Obtener la lista completa de pantallas capturadas para una aplicación específica.
 */
export function getCrawlerScreensForApp(appId: string, depthFilter?: 'MODERADO' | 'INTENSO'): AppCrawlerScreenAudit[] {
  const screens = APP_CRAWLER_SCREENS_REGISTRY[appId] || [];
  if (!depthFilter) return screens;
  if (depthFilter === 'MODERADO') {
    return screens.slice(0, Math.min(15, screens.length));
  }
  return screens;
}

/**
 * Obtener el total acumulado de pantallas mapeadas en todo el ecosistema.
 */
export function getTotalCrawlerScreensCount(): number {
  return Object.values(APP_CRAWLER_SCREENS_REGISTRY).reduce((acc, screens) => acc + screens.length, 0);
}
